import chalk from 'chalk';
import { writeFileSync, existsSync, readFileSync } from 'fs';
import { join } from 'path';

export function updateClaudeMd(projectRoot: string): void {
  const bundlePath = join(
    projectRoot, '.specflow', 'versions',
    getLatestVersion(projectRoot) ?? '', 'bundle.json'
  );

  if (!existsSync(bundlePath)) return;

  const bundle = JSON.parse(readFileSync(bundlePath, 'utf-8'));
  const claudeMdPath = join(projectRoot, 'CLAUDE.md');

  const content = generateClaudeMdFromBundle(bundle);
  writeFileSync(claudeMdPath, content, 'utf-8');

  console.log(chalk.green('  CLAUDE.md updated.'));
}

function getLatestVersion(projectRoot: string): string | null {
  const dir = join(projectRoot, '.specflow', 'versions');
  if (!existsSync(dir)) return null;
  const versions = require('fs').readdirSync(dir).filter((d: string) => d.startsWith('v')).sort();
  return versions.length > 0 ? versions[versions.length - 1] : null;
}

function generateClaudeMdFromBundle(bundle: Record<string, unknown>): string {
  const data = bundle['data'] as Record<string, unknown> | undefined;
  const overview = data?.['overview'] as Record<string, unknown> | undefined;
  const oq = bundle['metadata'] as Record<string, unknown> | undefined;
  const oqCount = oq?.['openQuestionCount'] ?? 0;
  const version = bundle['version'] ?? 'unknown';
  const createdAt = bundle['createdAt'] ?? '';

  return [
    `# ${overview?.['name'] ?? 'Project'} — SpecFlow AI Context`,
    '',
    `> Generated by SpecFlow AI. Version: ${version}`,
    `> Last sync: ${createdAt}`,
    '',
    '## Read First',
    '1. `docs/spec-flow/00_overview.md` — Project overview',
    '2. `docs/spec-flow/01_product_spec.md` — Product specifications',
    '3. `docs/spec-flow/03_technical_constraints.md` — Technical constraints',
    '4. `docs/spec-flow/06_agent_instructions.md` — Agent operating instructions',
    '',
    '## Critical Rules',
    '- Check `docs/spec-flow/07_open_questions.md` before making assumptions',
    '- Follow task order in `docs/spec-flow/05_task_breakdown.md`',
    '- Adhere to constraints in `docs/spec-flow/03_technical_constraints.md`',
    '- Reference `docs/spec-flow/08_decision_log.md` for past decisions',
    '',
    oqCount ? `${oqCount} open question(s) remain.` : 'No open questions.',
    '',
    '---',
    `Bundle: ${version} | ${createdAt}`,
  ].join('\n');
}
